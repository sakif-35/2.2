.MODEL SMALL
.STACK 100H
.DATA
    ENDL DB 0DH,0AH,'$'
.CODE
MAIN PROC
    
    MOV AX,@DATA
    MOV DS,AX
    
    MOV CX,5
    INPUT:
    XOR AX,AX
    CALL INDEC
    PUSH AX
    LOOP INPUT
    
    MOV CX,5
    OUTPUT:
    XOR AX,AX
    POP AX
    CALL OUTDEC
    LEA DX,ENDL
    MOV AH,09H
    INT 21H
    LOOP OUTPUT  

    MOV AH,4CH
    INT 21H
  
MAIN ENDP
INCLUDE INDEC.ASM
INCLUDE OUTDEC.ASM
END MAIN