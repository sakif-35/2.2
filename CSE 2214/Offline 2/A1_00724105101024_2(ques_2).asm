.MODEL SMALL
.STACK 100H

.DATA
MSG1 DB '$'
MSG2 DB 0DH,0AH,'VOWELS: $'
MSG3 DB 0DH,0AH,'SPECIAL CHARACTERS: $'

VOWELS DB 0
SPECIAL DB 0

.CODE
MAIN PROC

    MOV AX,@DATA
    MOV DS,AX

    MOV AH,9
    LEA DX,MSG1
    INT 21H

AGAIN:

    MOV AH,1
    INT 21H

    CMP AL,0DH
    JE PRINT

    CMP AL,'a'
    JE COUNT_VOWEL
    CMP AL,'e'
    JE COUNT_VOWEL
    CMP AL,'i'
    JE COUNT_VOWEL
    CMP AL,'o'
    JE COUNT_VOWEL
    CMP AL,'u'
    JE COUNT_VOWEL

    CMP AL,'0'
    JB COUNT_SPECIAL

    CMP AL,'9'
    JBE AGAIN

    CMP AL,'a'
    JB COUNT_SPECIAL

    CMP AL,'z'
    JBE AGAIN

COUNT_SPECIAL:
    INC SPECIAL
    JMP AGAIN

COUNT_VOWEL:
    INC VOWELS
    JMP AGAIN

PRINT:

    MOV AH,9
    LEA DX,MSG2
    INT 21H

    MOV DL,VOWELS
    ADD DL,30H
    MOV AH,2
    INT 21H

    MOV AH,9
    LEA DX,MSG3
    INT 21H

    MOV DL,SPECIAL
    ADD DL,30H
    MOV AH,2
    INT 21H

    MOV AH,4CH
    INT 21H

MAIN ENDP
END MAIN